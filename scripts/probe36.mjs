import { chromium } from 'playwright';
import path from 'node:path';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
await context.addInitScript(() => localStorage.setItem('terrain-o:onboarding-v1', 'seen'));
const page = await context.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.route('**/*', (route) => {
  const url = route.request().url();
  if (/overpass|openstreetmap|terrarium|elevation|s3\.amazonaws|terrain/.test(url)) return route.abort();
  return route.continue();
});
await page.goto('http://127.0.0.1:5199/', { waitUntil: 'networkidle' });
await page.locator('[data-testid="file-input"]').setInputFiles([path.resolve('e2e/fixtures/alpine.png'), path.resolve('e2e/fixtures/alpine.jgw')]);
await page.waitForFunction(() => document.body.innerText.includes('800 × 600'), null, { timeout: 30000 });
await page.getByRole('tab', { name: 'OSM' }).click();
await page.getByTestId('fetch-osm').click();
await page.waitForTimeout(6000);
console.log('OSM panel after failure:', (await page.locator('.dock-left').innerText()).split('\n').filter(l => /errore|non riuscit|fallit|rete|Overpass/i.test(l)).join(' | ').slice(0, 300));
console.log('OSM fetch disabled?', await page.getByTestId('fetch-osm').isDisabled());
await page.getByRole('tab', { name: 'DEM' }).click();
await page.getByTestId('generate-dem').click();
await page.waitForTimeout(6000);
console.log('DEM panel after failure:', (await page.locator('.dock-left').innerText()).split('\n').filter(l => /errore|non riuscit|fallit|rete|DEM/i.test(l)).join(' | ').slice(0, 300));
console.log('DEM generate disabled?', await page.getByTestId('generate-dem').isDisabled());
console.log('errors:', errors.length ? [...new Set(errors)].slice(0, 6) : 'none');
await browser.close();
