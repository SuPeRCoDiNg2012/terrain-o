import { chromium } from 'playwright';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
await context.addInitScript(() => localStorage.setItem('terrain-o:onboarding-v1', 'seen'));
const page = await context.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://127.0.0.1:5199/', { waitUntil: 'networkidle' });
await page.waitForTimeout(600);
console.log('title:', await page.title());
console.log('body overflow x:', await page.evaluate(() => document.documentElement.scrollWidth + '/' + window.innerWidth));
console.log('text head:', (await page.locator('body').innerText()).split('\n').slice(0, 12).join(' | '));
console.log('menu toggle visible:', await page.locator('.menu-mobile-toggle').isVisible());
console.log('palette visible:', await page.locator('.tool-palette').isVisible().catch(()=>false));
console.log('map bounds:', JSON.stringify(await page.locator('.map-stage').boundingBox().catch(()=>null)));
await page.screenshot({ path: 'screenshots/120-mobile.png' });
await page.locator('.menu-mobile-toggle').click();
await page.waitForTimeout(300);
console.log('mobile menu open text:', (await page.locator('.menu-bar-items').innerText()).split('\n').slice(0, 12).join(' | '));
await page.screenshot({ path: 'screenshots/121-mobile-menu.png' });
console.log('errors:', errors.length ? [...new Set(errors)].slice(0,6) : 'none');
await browser.close();
