import { chromium } from 'playwright';
import path from 'node:path';
import fs from 'node:fs';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, acceptDownloads: true });
await context.addInitScript(() => localStorage.setItem('terrain-o:onboarding-v1', 'seen'));
const page = await context.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('PAGE: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource|net::ERR/.test(m.text())) errors.push('CON: ' + m.text()); });
await page.goto('http://127.0.0.1:5199/', { waitUntil: 'networkidle' });
await page.locator('[data-testid="file-input"]').setInputFiles([path.resolve('e2e/fixtures/alpine.png'), path.resolve('e2e/fixtures/alpine.jgw')]);
await page.waitForFunction(() => document.body.innerText.includes('800 × 600'), null, { timeout: 30000 });
await page.getByRole('menuitem', { name: 'Classificazione' }).click();
await page.getByRole('menuitem', { name: 'Esegui con i parametri correnti' }).click();
await page.waitForTimeout(12000);
await page.getByRole('tab', { name: /Vettoriz/i }).click();
const panel = page.locator('.dock-right');
await panel.getByRole('button', { name: /Applica come livelli auto/i }).click();
await page.getByTestId('dialog-confirm').click();
await page.waitForTimeout(20000);
console.log('counters:', (await panel.innerText()).split('\n').filter(l=>/poligon|fori|scart|ms/i.test(l)).slice(0,4).join(' | '));
console.log('features:', await page.evaluate(() => document.querySelector('.status-bar')?.textContent));
console.log('job result:', (await panel.innerText()).split('\n').filter(l=>/geometri|element|Element|complet/i.test(l)).slice(0,6).join(' | '));
// export modal
await page.keyboard.press('Control+e');
await page.waitForTimeout(800);
const modal = page.locator('.dialog-panel');
console.log('modal open:', await modal.isVisible());
const dl = page.waitForEvent('download', { timeout: 10000 });
await page.getByTestId('geojson').click();
const download = await dl;
const target = '/tmp/' + download.suggestedFilename();
await download.saveAs(target);
const gj = JSON.parse(fs.readFileSync(target, 'utf8'));
const polys = gj.features.filter(f => /Polygon/.test(f.geometry.type));
const coords = polys.flatMap(f => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates));
console.log('geojson features:', gj.features.length, 'polygons:', polys.length, 'props:', JSON.stringify(polys[0]?.properties).slice(0,220));
console.log('first ring pts:', coords[0]?.[0]?.length, 'closed:', JSON.stringify(coords[0]?.[0]?.[0]) === JSON.stringify(coords[0]?.[0]?.at(-1)));
console.log('errors:', errors.length ? [...new Set(errors)].slice(0,8) : 'none');
await page.screenshot({ path: 'screenshots/124-vector-done.png' });
await browser.close();
