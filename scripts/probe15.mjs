import { chromium } from 'playwright';
import path from 'node:path';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
await context.addInitScript(() => localStorage.setItem('terrain-o:onboarding-v1', 'seen'));
const page = await context.newPage();
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(`console: ${m.text()}`); });
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
await page.goto('http://127.0.0.1:5199/', { waitUntil: 'networkidle' });
await page.locator('[data-testid="file-input"]').setInputFiles([path.resolve('e2e/fixtures/alpine.png'), path.resolve('e2e/fixtures/alpine.jgw')]);
await page.waitForFunction(() => document.body.innerText.includes('800 × 600'), null, { timeout: 30000 });
await page.getByRole('tab', { name: 'Classificazione' }).click();
await page.waitForTimeout(1200);
console.log('preview before apply:', await page.locator('.dock-right').innerText().then(t => t.includes('Anteprima')));
await page.screenshot({ path: 'screenshots/95-classify-before.png' });
await page.getByRole('button', { name: 'Applica classificazione' }).click();
await page.locator('.stats-block').waitFor({ state: 'visible', timeout: 90000 });
await page.waitForTimeout(800);
console.log('stats:', (await page.locator('.stats-block').innerText()).replace(/\n+/g,' | ').slice(0,300));
await page.screenshot({ path: 'screenshots/96-classified.png' });
await page.getByRole('tab', { name: 'Vettoriz.' }).click();
await page.waitForTimeout(1000);
await page.getByRole('button', { name: 'Applica come livelli auto' }).click();
await page.getByTestId('dialog-confirm').click();
await page.waitForTimeout(6000);
console.log('counters:', (await page.locator('.counter-row').innerText()).replace(/\n+/g,' | '));
await page.getByRole('button', { name: 'Valida topologia' }).click();
await page.waitForTimeout(800);
console.log('topology:', (await page.locator('.dock-right').innerText()).split('\n').filter(l => /topolog/i.test(l)).join(' | ').slice(0,300));
await page.getByRole('tab', { name: 'Elementi' }).click();
await page.waitForTimeout(500);
console.log('features:', await page.locator('.feature-row').count());
await page.screenshot({ path: 'screenshots/97-vectorized.png' });
console.log('ERRORS:', errors.length ? errors.join('\n') : 'none');
await browser.close();
